/**
 * Copies the Firebase settings into each Expo app's .env.local.
 *   npm run env:sync
 *
 * Reads the repo-root .env.local. If there isn't one yet, it uses your existing
 * apps/web/.env.local and converts NEXT_PUBLIC_FIREBASE_* to EXPO_PUBLIC_FIREBASE_*.
 * .env.local files are git-ignored: your keys never get committed.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const APPS = ['customer', 'store-admin', 'driver', 'super-admin']

const rootEnv = join(root, '.env.local')
const webEnv = join(root, 'apps', 'web', '.env.local')
const source = existsSync(rootEnv) ? rootEnv : existsSync(webEnv) ? webEnv : null

if (!source) {
  console.error('✖ No .env.local found. Copy .env.example to .env.local at the repo root and fill it in.')
  process.exit(1)
}

const lines = readFileSync(source, 'utf8')
  .split(/\r?\n/)
  .map((l) => l.trim())
  .filter((l) => l && !l.startsWith('#'))
  .map((l) => l.replace(/^NEXT_PUBLIC_/, 'EXPO_PUBLIC_'))
  .filter((l) => l.startsWith('EXPO_PUBLIC_'))

if (!lines.some((l) => l.startsWith('EXPO_PUBLIC_FIREBASE_PROJECT_ID='))) {
  console.warn('⚠ No FIREBASE_PROJECT_ID found. Only emulator mode will work.')
}

const body = `# Generated by npm run env:sync from ${source === rootEnv ? '.env.local' : 'apps/web/.env.local'}. Don't edit here.\n${lines.join('\n')}\n`
for (const app of APPS) {
  writeFileSync(join(root, 'apps', app, '.env.local'), body)
  console.log(`✔ apps/${app}/.env.local`)
}
